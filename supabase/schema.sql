create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text unique not null,
  customer_name text not null,
  email text not null,
  phone text not null default '',
  address text not null default '',
  items jsonb not null default '[]'::jsonb,
  subtotal numeric not null default 0,
  shipping numeric not null default 0,
  total numeric not null default 0,
  status text not null default 'Pending',
  channel text not null default 'Online',
  created_at timestamptz not null default now()
);
create index if not exists orders_created_at_idx on public.orders (created_at desc);
alter table public.orders enable row level security;
drop policy if exists "Allow checkout inserts" on public.orders;
create policy "Allow checkout inserts" on public.orders for insert to anon, authenticated with check (true);
drop policy if exists "Allow reading orders" on public.orders;
create policy "Allow reading orders" on public.orders for select to anon, authenticated using (true);
drop policy if exists "Allow order updates" on public.orders;
create policy "Allow order updates" on public.orders for update to anon, authenticated using (true) with check (true);
drop policy if exists "Allow order deletes" on public.orders;
create policy "Allow order deletes" on public.orders for delete to anon, authenticated using (true);
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  type text not null default 'Snacking',
  category text not null default 'Snacking',
  price numeric not null default 0,
  stock integer not null default 0,
  status text not null default 'In stock',
  image text not null default '/nut-selection.png',
  detail text not null default '',
  rating numeric not null default 4.9,
  reviews_count integer not null default 0,
  origin text not null default 'India',
  nutrients text[] not null default '{}',
  varieties jsonb not null default '[]'::jsonb,
  active boolean not null default true,
  updated_at timestamptz not null default now()
);
-- Upgrade path for databases created before varieties existed:
alter table public.products add column if not exists varieties jsonb not null default '[]'::jsonb;
create index if not exists products_active_idx on public.products (active);
-- Fix for tables created earlier with GENERATED ALWAYS (allows explicit id seeds):
alter table public.products alter column id drop identity if exists;
alter table public.products alter column id add generated by default as identity;
alter table public.products enable row level security;
drop policy if exists "Public can read products" on public.products;
create policy "Public can read products" on public.products for select to anon, authenticated using (true);
drop policy if exists "Allow product inserts" on public.products;
create policy "Allow product inserts" on public.products for insert to anon, authenticated with check (true);
drop policy if exists "Allow product updates" on public.products;
create policy "Allow product updates" on public.products for update to anon, authenticated using (true) with check (true);
drop policy if exists "Allow product deletes" on public.products;
create policy "Allow product deletes" on public.products for delete to anon, authenticated using (true);

